function Sumar(a, b) {
  
    return a + b;
}
console.log("Suma de 4 + 5 es: " + Sumar(4, 5));
function Restar(c, d) {

    return c - d;
}
console.log("Resta de 3 - 6 es: " + Restar(3, 6));
function Multiplicar(e, f) {
    
    return e * f;
}
console.log("Multiplicación de 2 * 7 es: " + Multiplicar(2, 7));
function Dividir(g, h) {
 
    return g / h;
}
console.log("División de 20 / 4 es: " + Dividir(20, 4));